実際の業務、資格、契約、組織によっては、専門事務職には「技術・人文知識・国際業務」が該当する場合があります。実際に事業を運営・管理する場合は「経営・管理」が該当することもありますが、日本法が指定資格を要件とする法律・会計業務を、無資格者が行えるようになるわけではありません。

