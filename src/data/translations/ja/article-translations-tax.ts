以前の雇用主へ速やかに請求してください。国税庁の案内では一般に、従業員用の写しは翌年1月31日まで、または年の途中で退職した場合は退職後1か月以内に交付する必要があります。新しい雇用主が以前の給与と源泉徴収額を確認できない場合、年末調整の金額を推測することはできません。

給与担当者へ情報を渡した後も、源泉徴収票を保管してください。確定申告、自治体手続き、融資、出入国在留管理上の証明、後の修正に必要となる場合があります。

