type Fields = Readonly<Record<string, string>>;

/** Prefixes every key in `fields` with `prefix.`, for one version's or variant's fields. */
function under(prefix: string, fields: Fields): Fields {
  return Object.fromEntries(Object.entries(fields).map(([key, value]) => [`${prefix}.${key}`, value]));
}

function defineDocumentTranslation(familyId: string, sourceRevision: string, ...parts: readonly Fields[]): TranslationArtifact {
  return translationArtifactSchema.parse({
    schemaVersion: 1,
    contentKind: "annotated-document",
    contentId: familyId,
    sourceLocale: "en",
    targetLocale: "ja",
    sourceRevision,
    terminologyRevision: localGuidanceTerminologyRevision,
    promptRevision: japaneseLocalGuidancePromptRevisions["2026-09-26-r2"],
    generator,
    fields: Object.assign({}, ...parts),
    availability: "active",
    reviewState: "machine-translated",
    generatedAt,
  });
}

