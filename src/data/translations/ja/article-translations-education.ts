学生本人が行う住所、学校変更、在留資格の維持、在留期間更新、就労許可、再入国、出国に関する手続きは別のものです。教育機関が報告しても、学生本人の届出が完了したり、在留資格が変更または延長されたりするわけではありません。

転校、休学、退学、除籍、卒業、長期欠席、所在不明、連絡不能、教育機関の閉鎖、認定状況の変更について、確認先を定めた手順を作成してください。分かっている事実を記録し、必要に応じて学生へ連絡し、機密情報を保護し、教育機関に適用される報告期限を守り、学生本人が次に行う手続きの担当機関へ案内してください。

