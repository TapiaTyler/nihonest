リチウムイオン電池と、それを含む製品は、破損したり圧力がかかったりすると発火することがあります。普通のごみ袋に隠して入れないでください。自治体が指定する電池または小型家電の回収方法に従い、案内がある場合は端子を保護し、電池が膨らんでいる、破損している、取り外せないときは担当者に伝えてください。事業から出るごみには、別の事業系廃棄物の手続きが適用されます。

