import { mkdtemp, mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, dirname, basename, resolve } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { generatedArticleMetadata } from "@/data/generated/article-metadata";
import { readOrderedArticleMetadata, serializeArticleMetadataModule } from "./article-metadata-producer";
import { validateArticleMetadataReferences } from "./article-metadata-validation";

const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map((root) => {
  if (dirname(resolve(root)) !== resolve(tmpdir()) || !basename(root).startsWith("nihonest-metadata-")) {
    throw new Error("Refusing cleanup outside the owned fixture directory.");
  }
  return rm(root, { recursive: true, force: true });
})); });
async function fixture() {
  const root = await mkdtemp(join(tmpdir(), "nihonest-metadata-")); roots.push(root);
  const registry = join(root, "src/lib/content/article-registry");
  const articles = join(root, "content/articles");
  await mkdir(registry, { recursive: true }); await mkdir(articles, { recursive: true });
  const catalog = join(root, "src/lib/content/articles.ts");
  const family = join(registry, "fixture.ts");
  await writeFile(catalog, 'import { family } from "@/lib/content/article-registry/fixture";\nconst entries = [...family] as const;\n');
  await writeFile(family, 'import Alpha, { metadata as alpha } from "../../../../content/articles/alpha.mdx";\n'
    + 'import Beta, { metadata as beta } from "../../../../content/articles/beta.mdx";\n'
    + 'export const family = [[beta, Beta], [alpha, Alpha]] as const;\n');
  for (const id of ["alpha", "beta"]) await writeFile(join(articles, `${id}.mdx`),
    `export const metadata = ${JSON.stringify({ ...generatedArticleMetadata[0], id, slug: id })}\n\n# Body need not be executed.\n`);
  return { root, catalog, family, articles };
}
async function edit(path: string, change: (text: string) => string) { await writeFile(path, change(await readFile(path, "utf8"))); }

describe("ordered metadata producer", () => {
  it("uses tuple order rather than import/file/ID order and treats body-only changes as the same metadata", async () => {
    const f = await fixture();
    const first = await readOrderedArticleMetadata(f.root);
    expect(first.map(({ id }) => id)).toEqual(["beta", "alpha"]);
    await edit(join(f.articles, "alpha.mdx"), (text) => text + "\n<UnknownComponent /><script>not executed</script>\n");
    expect(serializeArticleMetadataModule(await readOrderedArticleMetadata(f.root))).toBe(serializeArticleMetadataModule(first));
  });
  it("changes generated bytes for metadata edits and registration reorder", async () => {
    const f = await fixture(); const first = serializeArticleMetadataModule(await readOrderedArticleMetadata(f.root));
    await edit(join(f.articles, "alpha.mdx"), (text) => text.replace('"title":', '"title":"New title", "oldTitle":'));
    expect(serializeArticleMetadataModule(await readOrderedArticleMetadata(f.root))).not.toBe(first);
    await edit(f.family, (text) => text.replace("[[beta, Beta], [alpha, Alpha]]", "[[alpha, Alpha], [beta, Beta]]"));
    expect((await readOrderedArticleMetadata(f.root)).map(({ id }) => id)).toEqual(["alpha", "beta"]);
  });
  it.each(["assembly", "duplicate-family", "expression", "pair", "duplicate-tuple", "side-effect", "unused-import", "syntax", "unregistered", "duplicate-id"])
    ("rejects unsupported or incomplete %s registrations", async (mode) => {
      const f = await fixture();
      if (mode === "assembly") await edit(f.catalog, (text) => text.replace("...family", "family.map(x => x)"));
      if (mode === "duplicate-family") await edit(f.catalog, (text) => text.replace("...family", "...family, ...family"));
      if (mode === "expression") await edit(f.family, (text) => text.replace("[[beta, Beta], [alpha, Alpha]]", "makeEntries()"));
      if (mode === "pair") await edit(f.family, (text) => text.replace("[beta, Beta]", "[beta, Alpha]"));
      if (mode === "duplicate-tuple") await edit(f.family, (text) => text.replace("[alpha, Alpha]", "[beta, Beta]"));
      if (mode === "side-effect") await edit(f.family, (text) => text + "\nfamily.reverse();\n");
      if (mode === "unused-import") await edit(f.family, (text) => text.replace("[beta, Beta], ", ""));
      if (mode === "syntax") await edit(f.family, (text) => text + "\nexport const broken = ;");
      if (mode === "unregistered") await writeFile(join(f.articles, "unregistered.mdx"), await readFile(join(f.articles, "alpha.mdx")));
      if (mode === "duplicate-id") await writeFile(join(f.articles, "beta.mdx"), await readFile(join(f.articles, "alpha.mdx")));
      await expect(readOrderedArticleMetadata(f.root)).rejects.toThrow();
    });
  it("runs the existing collection/reference rules before canonical output can be accepted", () => {
    expect(() => validateArticleMetadataReferences(generatedArticleMetadata)).not.toThrow();
    const invalid = structuredClone(generatedArticleMetadata);
    invalid[0]!.sourceIds = ["unknown-source"];
    expect(() => validateArticleMetadataReferences(invalid)).toThrow();
  });
});
